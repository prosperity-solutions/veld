/**
 * A QR encoder, written rather than installed.
 *
 * `vite-plugin-singlefile` base64-inlines every asset into `index.html`, which is
 * then embedded in the daemon binary — so a dependency here is permanent bytes in
 * every veld release, for one panel. This covers exactly what that panel needs and
 * nothing else: **byte mode, error level M, versions 1–10**. Anything longer than that
 * returns `null` and the caller keeps showing the link.
 *
 * Scope, stated so the next person does not go looking for the general case:
 *
 * - **Byte mode only.** A URL is not alphanumeric-mode material (the mode's charset
 *   has no lowercase letters), so the numeric and alphanumeric modes would never be
 *   selected for the one payload this encodes. Kanji mode likewise.
 * - **Error level M** (~15% recovery), the level essentially every URL QR uses. L
 *   would buy ~20% more capacity we do not need; Q and H shrink capacity for a code
 *   that is being scanned off a bright screen from 20cm away.
 * - **Versions 1–10**, i.e. up to 214 payload bytes. A gateway URL with a password
 *   fragment is ~120. Beyond that the honest answer is "too long to scan", not a
 *   53×53 grid of 1px modules on a phone screen.
 *
 * Correctness is pinned by `qr.test.ts`, which compares whole matrices against
 * fixtures generated by the `qrcode` PyPI package plus a from-the-spec mask scorer (see
 * `qrFixtures.ts` — `segno` was tried first and turned out to emit a spurious pad
 * codeword) — including a case per version boundary and one per mask. That is the only
 * kind of test worth having here: an encoder that is subtly wrong still renders a
 * plausible square, and no amount of reading the code tells you a scanner can read it.
 *
 * Pure and DOM-free on purpose, like the rest of `shared/` — `vitest` runs with
 * `environment: "node"`.
 */

/** Payload capacity in bytes at error level M, indexed by version − 1. */
const MAX_BYTES_M = [14, 26, 42, 62, 84, 106, 122, 152, 180, 213] as const;

/**
 * Per-version block structure at error level M.
 *
 * `groups` is `[blockCount, dataCodewordsPerBlock]` pairs, in the order the spec
 * lists them — group 2's blocks are one codeword longer than group 1's, which is
 * what makes the interleave at the end non-trivial. Transcribed from ISO/IEC
 * 18004 table 9 via `segno`'s tables rather than typed from memory, and pinned by
 * the fixture tests: a wrong `ecPerBlock` here produces a scannable-looking code
 * that no scanner accepts.
 */
interface VersionSpec {
  /** Total codewords (data + error correction) in the symbol. */
  total: number;
  /** Error-correction codewords per block. Uniform across groups by construction. */
  ecPerBlock: number;
  groups: readonly (readonly [number, number])[];
  /** Alignment-pattern centre coordinates, empty for version 1. */
  align: readonly number[];
}

const VERSIONS: readonly VersionSpec[] = [
  { total: 26, ecPerBlock: 10, groups: [[1, 16]], align: [] },
  { total: 44, ecPerBlock: 16, groups: [[1, 28]], align: [6, 18] },
  { total: 70, ecPerBlock: 26, groups: [[1, 44]], align: [6, 22] },
  { total: 100, ecPerBlock: 18, groups: [[2, 32]], align: [6, 26] },
  { total: 134, ecPerBlock: 24, groups: [[2, 43]], align: [6, 30] },
  { total: 172, ecPerBlock: 16, groups: [[4, 27]], align: [6, 34] },
  { total: 196, ecPerBlock: 18, groups: [[4, 31]], align: [6, 22, 38] },
  { total: 242, ecPerBlock: 22, groups: [[2, 38], [2, 39]], align: [6, 24, 42] },
  { total: 292, ecPerBlock: 22, groups: [[3, 36], [2, 37]], align: [6, 26, 46] },
  { total: 346, ecPerBlock: 26, groups: [[4, 43], [1, 44]], align: [6, 28, 50] },
];

/** The error-level bits for M, as they appear in the format information. */
const ECC_BITS_M = 0b00;

// ---------------------------------------------------------------------------
// GF(256), the field the Reed–Solomon codewords live in.
// ---------------------------------------------------------------------------

/**
 * Log/antilog tables for GF(2^8) with the QR primitive polynomial
 * x^8 + x^4 + x^3 + x^2 + 1 (0x11d) and generator 2.
 */
const EXP = new Uint8Array(256);
const LOG = new Uint8Array(256);
{
  let x = 1;
  for (let i = 0; i < 255; i++) {
    EXP[i] = x;
    LOG[x] = i;
    x <<= 1;
    if (x & 0x100) x ^= 0x11d;
  }
  // EXP is cyclic with period 255; the 256th entry keeps `mul` branch-free for
  // exponents that sum to exactly 255.
  EXP[255] = EXP[0];
}

function mul(a: number, b: number): number {
  if (a === 0 || b === 0) return 0;
  return EXP[(LOG[a] + LOG[b]) % 255];
}

/** The generator polynomial for `n` error-correction codewords, low degree last. */
function generatorPoly(n: number): Uint8Array {
  let poly = new Uint8Array([1]);
  for (let i = 0; i < n; i++) {
    const next = new Uint8Array(poly.length + 1);
    // Multiply by (x - α^i); subtraction is XOR in this field.
    for (let j = 0; j < poly.length; j++) {
      next[j] ^= poly[j];
      next[j + 1] ^= mul(poly[j], EXP[i]);
    }
    poly = next;
  }
  return poly;
}

/** The `n` error-correction codewords for one data block. */
function ecCodewords(data: Uint8Array, n: number): Uint8Array {
  const gen = generatorPoly(n);
  const rem = new Uint8Array(n);
  for (const byte of data) {
    const factor = byte ^ rem[0];
    rem.copyWithin(0, 1);
    rem[n - 1] = 0;
    if (factor !== 0) {
      // gen[0] is 1, so the leading term cancels and only the tail contributes.
      for (let i = 0; i < n; i++) rem[i] ^= mul(gen[i + 1], factor);
    }
  }
  return rem;
}

// ---------------------------------------------------------------------------
// Bit stream → codewords
// ---------------------------------------------------------------------------

class Bits {
  readonly bits: number[] = [];
  push(value: number, length: number): void {
    for (let i = length - 1; i >= 0; i--) this.bits.push((value >>> i) & 1);
  }
}

/**
 * The data codewords for `bytes` at `version`, padded to the version's capacity.
 *
 * The pad sequence is the spec's: a 4-bit terminator (truncated if the capacity
 * ends first), zeroes to the next byte boundary, then `0xEC 0x11` alternating.
 */
function dataCodewords(bytes: Uint8Array, version: number): Uint8Array {
  const spec = VERSIONS[version - 1];
  const dataLen = spec.groups.reduce((n, [count, len]) => n + count * len, 0);
  const capacity = dataLen * 8;
  const bits = new Bits();
  bits.push(0b0100, 4); // byte mode
  // The character-count field widens at version 10 — a fixed 8 bits would silently
  // truncate a 300-byte payload's length on the versions that can hold it.
  bits.push(bytes.length, version < 10 ? 8 : 16);
  for (const b of bytes) bits.push(b, 8);
  for (let i = 0; i < 4 && bits.bits.length < capacity; i++) bits.bits.push(0);
  while (bits.bits.length % 8 !== 0) bits.bits.push(0);

  const out = new Uint8Array(dataLen);
  for (let i = 0; i < bits.bits.length; i += 8) {
    let byte = 0;
    for (let j = 0; j < 8; j++) byte = (byte << 1) | bits.bits[i + j];
    out[i / 8] = byte;
  }
  for (let i = bits.bits.length / 8, alt = 0; i < dataLen; i++, alt++) {
    out[i] = alt % 2 === 0 ? 0xec : 0x11;
  }
  return out;
}

/**
 * Interleave data and error-correction codewords into the final byte stream.
 *
 * Column-major across blocks, which is what makes a burst of damage spread across
 * every block instead of destroying one.
 */
function interleave(data: Uint8Array, version: number): Uint8Array {
  const spec = VERSIONS[version - 1];
  const blocks: { data: Uint8Array; ec: Uint8Array }[] = [];
  let offset = 0;
  for (const [count, len] of spec.groups) {
    for (let i = 0; i < count; i++) {
      const block = data.subarray(offset, offset + len);
      offset += len;
      blocks.push({ data: block, ec: ecCodewords(block, spec.ecPerBlock) });
    }
  }
  const out: number[] = [];
  const maxData = Math.max(...blocks.map((b) => b.data.length));
  for (let i = 0; i < maxData; i++) {
    for (const b of blocks) if (i < b.data.length) out.push(b.data[i]);
  }
  for (let i = 0; i < spec.ecPerBlock; i++) {
    for (const b of blocks) out.push(b.ec[i]);
  }
  return new Uint8Array(out);
}

