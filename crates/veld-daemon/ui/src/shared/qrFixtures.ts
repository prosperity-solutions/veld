/**
 * Reference QR symbols from an independent implementation.
 *
 * Generated, never hand-written — a hand-written expectation for a QR matrix is only
 * a transcription of the encoder under test. Produced by the `qrcode` PyPI package
 * (pure Python, no relation to `qr.ts`) plus a from-the-spec mask scorer; the
 * generator needs a Python environment CI does not have, so it lives in the PR that
 * introduced this file rather than in the repo.
 *
 * Two sets, pinning two different things:
 *
 * - `AUTO` — one symbol per version 1–10 plus three share-shaped URLs, each at the
 *   mask the spec's penalty rules select. `qrcode`'s *own* mask choice is
 *   deliberately not used: its penalty implementation deviates from ISO 18004 7.8.3
 *   on some symbols, so the generator re-scored all eight candidates with a
 *   from-the-spec implementation and kept the argmin. That makes this a second
 *   opinion on `qr.ts`'s mask selection instead of a copy of one library's quirk.
 * - `MASKS` — one payload under all eight masks. Pins masking and the format bits
 *   independently of which mask the penalty prefers.
 *
 * Two reference deviations found while building this, worth not rediscovering:
 * `segno` appends a spurious `0x00` pad codeword whenever the bit stream is already
 * byte-aligned — which in byte mode it always is — so its matrices disagree with both
 * `qrcode` and this encoder from the fourth codeword on. And `qrcode` picks a
 * different mask from the spec argmin on roughly a third of payloads. Neither
 * produces an unscannable symbol, which is exactly why pinning against one
 * implementation would not have been enough.
 *
 * `rows` is one string per row, `1` for a dark module, no quiet zone — the same
 * orientation as `QrMatrix.modules`.
 */

